package simulation.Model;

/**
 *
 * @author tunyaa
 */
public class RowColumn {

    int row;
    int col;

    public RowColumn(int row, int col) {
        this.row = row;
        this.col = col;
    }

    public int getRow() {
        return row;
    }

    public void setRow(int row) {
        this.row = row;
    }

    public int getCol() {
        return col;
    }

    public void setCol(int col) {
        this.col = col;
    }
}
